import { lstat, readFile, readdir } from "node:fs/promises";
import { join, resolve } from "node:path";

function fail(message) {
  throw new Error(`static origin audit failed: ${message}`);
}

function parseArguments(arguments_) {
  const values = new Map();
  for (let index = 0; index < arguments_.length; index += 2) {
    const name = arguments_[index];
    const value = arguments_[index + 1];
    if (!name?.startsWith("--") || value === undefined) {
      fail(
        "usage: audit-static-origin --origin HTTPS_ORIGIN --site SITE_DIRECTORY",
      );
    }
    if (values.has(name)) fail(`duplicate option: ${name}`);
    values.set(name, value);
  }
  if (values.size !== 2 || !values.has("--origin") || !values.has("--site")) {
    fail(
      "usage: audit-static-origin --origin HTTPS_ORIGIN --site SITE_DIRECTORY",
    );
  }
  const origin = new URL(values.get("--origin"));
  if (
    origin.protocol !== "https:" ||
    origin.username !== "" ||
    origin.password !== "" ||
    origin.pathname !== "/" ||
    origin.search !== "" ||
    origin.hash !== ""
  ) {
    fail(
      "origin must be an HTTPS origin without credentials, path, query, or fragment",
    );
  }
  return { origin, site: resolve(values.get("--site")) };
}

async function generatedFiles(root, current = root) {
  const metadata = await lstat(current);
  if (metadata.isSymbolicLink())
    fail(`symbolic link in generated site: ${current}`);
  if (!metadata.isDirectory())
    return [current.slice(root.length + 1).replaceAll("\\", "/")];

  const files = [];
  const entries = await readdir(current);
  entries.sort((left, right) => left.localeCompare(right));
  for (const entry of entries)
    files.push(...(await generatedFiles(root, join(current, entry))));
  return files;
}

async function request(url) {
  return fetch(url, {
    redirect: "follow",
    signal: AbortSignal.timeout(30_000),
  });
}

const { origin, site } = parseArguments(process.argv.slice(2));
const files = await generatedFiles(site);
for (const required of [
  "404.html",
  "_headers",
  "edgefossil-site.json",
  "index.html",
]) {
  if (!files.includes(required))
    fail(`required generated file is missing: ${required}`);
}

const deployable = files.filter(
  (path) => path !== "_headers" && path !== "404.html",
);
for (const path of deployable) {
  const urlPath = path.split("/").map(encodeURIComponent).join("/");
  const response = await request(new URL(urlPath, origin));
  const actual = Buffer.from(await response.arrayBuffer());
  const expected = await readFile(join(site, path));
  if (response.status !== 200)
    fail(`generated asset returned ${response.status}: ${path}`);
  if (!actual.equals(expected)) fail(`served bytes differ: ${path}`);
}

const index = await request(origin);
if (
  !index.headers.get("content-security-policy")?.includes("default-src 'none'")
) {
  fail("Content-Security-Policy is missing from the remote index");
}
if (index.headers.get("x-content-type-options") !== "nosniff") {
  fail("X-Content-Type-Options is missing from the remote index");
}

const missing = await request(
  new URL("edgefossil-remote-audit-missing", origin),
);
const missingBody = Buffer.from(await missing.arrayBuffer());
if (missing.status !== 404) fail(`missing route returned ${missing.status}`);
if (!missingBody.equals(await readFile(join(site, "404.html")))) {
  fail("remote 404 body differs from generated bytes");
}

const internalHeaders = await request(new URL("_headers", origin));
if (internalHeaders.status !== 404) fail("_headers is exposed remotely");

const manifest = JSON.parse(
  await readFile(join(site, "edgefossil-site.json"), "utf8"),
);
if (manifest.source?.realm !== "public")
  fail("generated manifest realm is not public");
console.log(
  `Static origin audit passed; files=${deployable.length}, status=200/404, semantic_root=${manifest.source.semantic_root}`,
);
